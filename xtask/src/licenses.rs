//! `xtask licenses`: writes `THIRD_PARTY_LICENSES.md` (SPEC.md §7 M8).
//!
//! Rust crates come from `cargo about generate` (accepted licences in
//! `about.toml`, template `licenses/about.hbs`). The native libraries that
//! ship next to the binary (ONNX Runtime, PDFium) are not crates, so their
//! licence texts are kept in `licenses/` and appended by hand; refresh them
//! when `ONNXRUNTIME_VERSION` or `PDFIUM_TAG` changes. The models section is
//! `licenses/models.md`.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use std::process::Command;

use anyhow::{Context, Result, bail};

use crate::{ONNXRUNTIME_VERSION, PDFIUM_TAG};

const OUTPUT: &str = "THIRD_PARTY_LICENSES.md";

pub fn licenses() -> Result<()> {
    // cargo-about refuses to write to a pipe on Windows, so via a file.
    let generated = "target/crates-licenses.md";
    let status = Command::new("cargo")
        .args(["about", "generate", "licenses/about.hbs", "-o", generated])
        .status()
        .context(
            "running `cargo about` (install: cargo install --locked cargo-about --features cli)",
        )?;
    if !status.success() {
        bail!("cargo about failed (see above)");
    }

    let mut out = String::new();
    out.push_str(
        "# Third-party licences\n\n\
         Magi is MIT-licensed. It ships the native libraries and Rust crates\n\
         below, and downloads the models listed under \"Models\" on demand.\n\
         Generated by `just licenses`; do not edit by hand.\n\n\
         ## Native libraries\n\n",
    );

    writeln!(
        out,
        "### ONNX Runtime {ONNXRUNTIME_VERSION}\n\n\
         Runs the models. <https://github.com/microsoft/onnxruntime>, MIT.\n"
    )?;
    code_block(&mut out, "licenses/onnxruntime/LICENSE")?;
    out.push_str("Third-party notices of ONNX Runtime:\n\n");
    code_block(&mut out, "licenses/onnxruntime/ThirdPartyNotices.txt")?;

    writeln!(
        out,
        "### PDFium ({PDFIUM_TAG})\n\n\
         Reads PDF files. Built by <https://github.com/bblanchon/pdfium-binaries>\n\
         (MIT); PDFium itself is BSD-3-Clause, and it bundles the components\n\
         whose licences follow.\n"
    )?;
    let mut pdfium: Vec<_> = fs::read_dir("licenses/pdfium")?
        .map(|e| e.map(|e| e.path()))
        .collect::<std::io::Result<_>>()?;
    pdfium.sort();
    for path in pdfium {
        let name = path.file_name().unwrap_or_default().to_string_lossy();
        writeln!(out, "#### {name}\n")?;
        code_block(&mut out, &path)?;
    }

    out.push_str(&fs::read_to_string("licenses/models.md")?);
    out.push('\n');
    out.push_str(&fs::read_to_string(generated)?);

    fs::write(OUTPUT, out)?;
    println!("wrote {OUTPUT}");
    Ok(())
}

/// Appends `path`'s text as a fenced block, with a fence longer than any
/// backtick run inside it.
fn code_block(out: &mut String, path: impl AsRef<Path>) -> Result<()> {
    let path = path.as_ref();
    let text = fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    let longest = text.split(|c| c != '`').map(str::len).max().unwrap_or(0);
    let fence = "`".repeat(longest.max(2) + 1);
    writeln!(out, "{fence}text\n{}\n{fence}\n", text.trim_end())?;
    Ok(())
}
